"""Stage self-signed TLS and Nginx settings for the Debian installer."""

import argparse
import ipaddress
from pathlib import Path
import shutil
import subprocess


def stage(address, output, certificate_dir):
    address = str(ipaddress.IPv4Address(address))
    if ipaddress.ip_address(address).is_unspecified or ipaddress.ip_address(address).is_multicast:
        raise ValueError('HTTPS requires a specific unicast IPv4 address')
    output.mkdir(parents=True, exist_ok=True)
    output.chmod(0o700)
    certificate_dir = certificate_dir.resolve()
    cert, key = certificate_dir / 'certificate.pem', certificate_dir / 'private-key.pem'
    staged_cert, staged_key = output / 'certificate.pem', output / 'private-key.pem'

    def openssl(*args):
        return subprocess.run(['openssl', *map(str, args)], capture_output=True, check=True).stdout

    reusable = False
    if cert.is_file() and key.is_file():
        try:
            openssl('x509', '-in', cert, '-noout', '-checkend', '2592000')
            openssl('verify', '-CAfile', cert, '-verify_ip', address, cert)
            reusable = openssl('x509', '-in', cert, '-pubkey', '-noout') == openssl(
                'pkey', '-in', key, '-pubout'
            )
        except subprocess.CalledProcessError:
            pass
    if reusable:
        shutil.copyfile(cert, staged_cert)
        shutil.copyfile(key, staged_key)
    else:
        openssl(
            'req',
            '-x509',
            '-newkey',
            'rsa:3072',
            '-sha256',
            '-nodes',
            '-days',
            '365',
            '-keyout',
            staged_key,
            '-out',
            staged_cert,
            '-subj',
            '/CN=' + address,
            '-addext',
            'subjectAltName=IP:' + address,
            '-addext',
            'extendedKeyUsage=serverAuth',
        )
    staged_key.chmod(0o600)
    staged_cert.chmod(0o644)
    config = f'''# VSM Toolbox managed HTTPS — generated by install-debian13.sh
limit_conn_zone $binary_remote_addr zone=vsm_https_connections:10m;
limit_req_zone $binary_remote_addr zone=vsm_https_requests:10m rate=10r/s;
server {{
    listen {address}:80;
    server_name {address};
    return 301 https://{address}$request_uri;
}}
server {{
    listen {address}:443 ssl;
    server_name {address};
    ssl_certificate "{cert}";
    ssl_certificate_key "{key}";
    ssl_protocols TLSv1.2 TLSv1.3;
    client_header_timeout 15s;
    client_body_timeout 15s;
    send_timeout 30s;
    client_max_body_size 128m;
    limit_conn vsm_https_connections 32;
    limit_req zone=vsm_https_requests burst=40 nodelay;
    location / {{
        proxy_pass http://127.0.0.1:8080;
        proxy_set_header Host $host;
        proxy_set_header Connection close;
        proxy_connect_timeout 5s;
        proxy_read_timeout 125s;
        proxy_send_timeout 30s;
        proxy_request_buffering on;
        proxy_buffering on;
    }}
}}
'''
    (output / 'nginx.conf').write_text(config)
    (output / 'https.env').write_text('VSM_HOST=127.0.0.1\nVSM_PORT=8080\nVSM_COOKIE_SECURE=1\n')
    (output / 'https.conf').write_text('[Service]\nEnvironmentFile=/etc/vsm-toolbox/https.env\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ip', required=True)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--certificate-dir', type=Path, default=Path('/etc/vsm-toolbox/tls'))
    args = parser.parse_args()
    stage(args.ip, args.output, args.certificate_dir)
